def _compose_ft(g_t, h_t, q):
    """g(h(x)) for polynomials with F_q[t] coefficients (lists of lists)."""
    def norm(a):
        a = [c % q for c in a]
        while a and a[-1] == 0: a.pop()
        return a
    def add(a, b):
        out = [0] * max(len(a), len(b))
        for i, x in enumerate(a): out[i] += x
        for i, x in enumerate(b): out[i] += x
        return norm(out)
    def mul(a, b):
        if not a or not b: return []
        out = [0] * (len(a) + len(b) - 1)
        for i, x in enumerate(a):
            for j, y in enumerate(b):
                out[i + j] += x * y
        return norm(out)
    def pxmul(A, B):
        out = [[] for _ in range(len(A) + len(B) - 1)]
        for i, a in enumerate(A):
            for j, b in enumerate(B):
                out[i + j] = add(out[i + j], mul(a, b))
        return out
    out = [[]]
    for c in reversed(g_t):
        out = pxmul(out, h_t)
        out[0] = add(out[0], c)
    while len(out) > 1 and not out[-1]:
        out.pop()
    return [a if a else [0] for a in out]

def check_triangular(q: int, g_t, h_t, name: str, K: int = 30, verbose: bool = True) -> Dict:
    f_t = _compose_ft(g_t, h_t, q)
    n = len(f_t) - 1
    mh = len(h_t) - 1
    mg = len(g_t) - 1
    rec: Dict = {"family": "C", "name": name, "q": q, "MV": n, "deg_g": mg, "deg_h": mh, "f": f_t}
    import verify_roots as vr
    Fp = hf.Zmod(q)
    t0 = next(c for c in range(q) if vr._is_squarefree(Fp, [hf._peval(Fp, a, c) for a in f_t]))
    rec["t0"] = t0
    state = cf.FqtState(f_t, q, t0, K)
    # fibre blocks of h (proven): group roots by h(root)
    S = state.S
    h_S = [S.from_list([state.F.from_int(c) for c in hf._shift_poly_t(q, a, t0)]) for a in h_t]
    vals = [hf._peval(S, h_S, r) for r in state.roots_raw]
    blocks: List[List[int]] = []
    for j in range(n):
        for bl in blocks:
            if S.eq(vals[bl[0]], vals[j]):
                bl.append(j); break
        else:
            blocks.append([j])
    assert len(blocks) == mg and all(len(b) == mh for b in blocks)
    P = inv._canon(blocks)
    # starting group: full block stabilizer (proven since the fibration is over F_q(t)); small n only
    assert n <= 7, "triangular starting group is built by S_n enumeration (n <= 7)"
    Sm_top = pg.closure(inv.S_n(n), n)
    U0 = frozenset(x for x in Sm_top if all(frozenset(x[i] for i in b) in {frozenset(b2) for b2 in blocks} for b in blocks))
    G, _ = cf.galois_group_Fqt(state, e=1, verbose=False, U0=U0)
    Ggeo, _ = cf.galois_group_Fqt(state, e=state.s, verbose=False, U0=U0)
    c = len(G) // len(Ggeo)
    rec["G_order"], rec["G_geom_order"], rec["c"] = len(G), len(Ggeo), c
    # block quotient of G_geom vs the independently computed geometric monodromy of g
    piGgeo = frozenset(inv.induced_action(x, P) for x in Ggeo)
    rg = cf.run_A7(g_t, q, next(cc for cc in range(q) if vr._is_squarefree(Fp, [hf._peval(Fp, a, cc) for a in g_t])), verbose=False)
    rec["Mg_geom_order"] = rg["G_geom_order"]
    import itertools as it
    Gg = pg.closure([tuple(x) for x in rg["G_geom_gens"]], mg)
    rec["C1_block_quotient_is_Mg_geom"] = any(all(pg.compose(pi, pg.compose(x, pg.inverse(pi))) in Gg for x in pg.generating_set(piGgeo, mg))
                                              for pi in it.permutations(range(mg))) and len(piGgeo) == len(Gg)
    # local group and the wreath bound
    L, _ = inv.local_group(Ggeo, P[0])
    ker = frozenset(x for x in Ggeo if inv.induced_action(x, P) == pg.identity(mg))
    rec["L_order"], rec["kernel_order"] = len(L), len(ker)
    rec["C2_G_geom_in_L_wr_quotient"] = (len(Ggeo) == len(piGgeo) * len(ker)) and (len(L) ** mg) % len(ker) == 0
    rec["W_cl_order"] = (math.factorial(mh)) ** mg * rec["Mg_geom_order"]     # relative monodromy <= S_mh
    rec["C3_G_geom_in_W_cl"] = len(Ggeo) <= rec["W_cl_order"] and all(all(frozenset(x[i] for i in b) in set(P) for b in P) for x in Ggeo)
    rec["ok"] = all(rec[k] for k in ("C1_block_quotient_is_Mg_geom", "C2_G_geom_in_L_wr_quotient", "C3_G_geom_in_W_cl"))
    if verbose:
        print(f"F_{q} {name} MV={n}: |G|={len(G):3d} |G_geom|={len(Ggeo):3d} c={c} | quotient=M_g^geom({rec['Mg_geom_order']}) "
              f"{rec['C1_block_quotient_is_Mg_geom']} | L={len(L)} kernel={len(ker)} wreath bound {rec['C2_G_geom_in_L_wr_quotient']} | {'all ok' if rec['ok'] else 'FAILURE'}")
    return rec


