FAMILY_A = [(5, d) for d in (2, 3, 4, 6, 7, 8, 9, 11, 12, 13, 16, 18, 21, 24, 28, 33, 36)] + \
           [(3, d) for d in (5, 10, 20, 25, 34, 40)] + [(7, 40)]
FAMILY_B = [(5, 2, 2), (5, 3, 2), (5, 2, 3), (7, 2, 2), (7, 3, 2), (5, 4, 2), (7, 4, 2), (5, 2, 4),
            (7, 6, 2), (5, 7, 2), (11, 6, 2), (5, 8, 2), (13, 3, 3)]
FAMILY_C = [(5, [[0, 4], [0], [0], [1]], [[0, 4], [0], [1]], "g=y^3-t o h=x^2-t"),
            (7, [[6, 6], [0], [1]], [[0, 6], [6], [0], [1]], "g=y^2-(t+1) o h=x^3-x-t"),
            (5, [[0, 4], [4], [0], [1]], [[0, 4], [0], [1]], "g=y^3-y-t o h=x^2-t")]

def main(budget_s: Optional[float] = None, results_path: str = "family_sparse_results.json") -> List[Dict]:
    pg.load_subgroup_cache()
    results = json.load(open(results_path)) if os.path.exists(results_path) else []
    done = {json.dumps(r["key"]) for r in results if r.get("status") == "ok"}   # failures are retried
    t_all = time.time()
    jobs = [("A", (q, d, 1)) for q, d in FAMILY_A] + [("B", (q, d, m)) for q, d, m in FAMILY_B] + \
           [("C", (0, i)) for i in range(len(FAMILY_C))]
    for fam, key in jobs:
        kj = json.dumps([fam, key])
        if kj in done:
            continue
        if budget_s is not None and time.time() - t_all > budget_s:
            print(f"[budget reached: {len(results)} of {len(jobs)} jobs recorded]")
            break
        t0 = time.time()
        try:
            if fam in ("A", "B"):
                q, d, m = key
                rec = check_lacunary(q, d, m)
            else:
                q, i = key
                qq, g_t, h_t, name = FAMILY_C[i]
                rec = check_triangular(qq, g_t, h_t, name)
            rec["status"] = "ok"
        except (ArithmeticError, AssertionError) as e:
            rec = {"status": f"failed: {e}"}
            print(f"{fam} {key}: {rec['status']}")
        rec["key"] = [fam, key]
        rec["time_s"] = round(time.time() - t0, 1)
        if rec.get("status") == "ok":                          # drop superseded failed attempts for this key
            results = [r for r in results if r["key"] != rec["key"] or r.get("status") == "ok"]
        results.append(rec)
        pg.save_subgroup_cache()
        with open(results_path, "w") as fh:
            json.dump(results, fh, indent=1, default=str)
    oks = [r for r in results if r.get("status") == "ok"]
    print(f"\n{len(oks)} pencils checked / {len(results)} recorded")
    if oks:
        print("all classification checks pass:", all(r["ok"] for r in oks))
        lac = [r for r in oks if r["family"] in ("A", "B")]
        print("G_geom = W_cl (equality observed) in", sum(1 for r in lac if r["G_geom_equals_W_cl"]), "of", len(lac), "lacunary pencils")
        print("max MV checked:", max(r["MV"] for r in oks))
    return results


if __name__ == "__main__":
    budget = float(sys.argv[1]) if len(sys.argv) > 1 else None
    main(budget)