Perm = Tuple[int, ...]


def ord_mod(q: int, d: int) -> int:
    if d == 1:
        return 1
    s, x = 1, q % d
    while x != 1:
        x = (x * q) % d; s += 1
    return s

# ----------------------------------------------------------------------------
# fibration labelling and the classification groups in that labelling
# ----------------------------------------------------------------------------

def fibration_labels(state: cf.FqtState, d: int) -> Tuple[List[Tuple[int, int]], object]:
    """label each root as (fibre i, cyclic label k): roots in one fibre of
    x -> x^d differ by d-th roots of unity zeta^k (constants of F_{q^s});
    returns labels and the chosen primitive zeta."""
    S, F = state.S, state.F
    n = state.n
    roots = state.roots_raw
    pw = [S.pow(r, d) for r in roots]
    fibres: List[List[int]] = []
    for j in range(n):
        for fb in fibres:
            if S.eq(pw[fb[0]], pw[j]):
                fb.append(j); break
        else:
            fibres.append([j])
    assert all(len(fb) == d for fb in fibres), "fibres of x -> x^d are not uniform"
    # ratios within a fibre are constants (d-th roots of unity)
    def const_of(x):
        assert all(F.is_zero(c) for c in x[1:]), "root ratio is not constant: not a mu_d-torsor"
        return x[0]
    inv0 = S.inv(roots[fibres[0][0]])
    ratios = [const_of(S.mul(roots[j], inv0)) for j in fibres[0]]
    zeta = None
    for r in ratios:
        # order of r in F^*
        o, x = 1, r
        while not F.eq(x, F.one()):
            x = F.mul(x, r); o += 1
        if o == d:
            zeta = r; break
    assert zeta is not None, "no primitive d-th root of unity among the ratios"
    zpow = [F.one()]
    for _ in range(d - 1):
        zpow.append(F.mul(zpow[-1], zeta))
    labels: List[Optional[Tuple[int, int]]] = [None] * n
    for i, fb in enumerate(fibres):
        base = roots[fb[0]]
        binv = S.inv(base)
        for j in fb:
            c = const_of(S.mul(roots[j], binv))
            k = next(k for k in range(d) if F.eq(c, zpow[k]))
            labels[j] = (i, k)
    return labels, zeta

def classification_groups(labels: List[Tuple[int, int]], d: int, m: int, q: int):
    """W_cl = C_d wr S_m and A_cl = W_cl x| <q mod d> in the root labelling."""
    n = d * m
    idx = {lab: j for j, lab in enumerate(labels)}
    def perm_from_map(fmap):
        out = [0] * n
        for j, (i, k) in enumerate(labels):
            out[j] = idx[fmap(i, k)]
        return tuple(out)
    gens_W = [perm_from_map(lambda i, k: (i, (k + 1) % d) if i == 0 else (i, k))]
    if m >= 2:
        gens_W.append(perm_from_map(lambda i, k: ({0: 1, 1: 0}.get(i, i), k)))
        gens_W.append(perm_from_map(lambda i, k: ((i + 1) % m, k)))
    W_cl = pg.closure(gens_W, n)
    gens_A = gens_W + [perm_from_map(lambda i, k: (i, (q * k) % d))]
    A_cl = pg.closure(gens_A, n)
    return W_cl, A_cl

def affine_data(perm: Perm, labels, d: int, m: int):
    """if perm maps (i,k) -> (sigma(i), u k + b_i) with one multiplier u, return
    (u, sigma, b); else None."""
    idx = {lab: j for j, lab in enumerate(labels)}
    sigma = {}
    u_global = None
    b = {}
    for i in range(m):
        j0 = idx[(i, 0)]
        i2, b_i = labels[perm[j0]]
        sigma[i] = i2; b[i] = b_i
        if d >= 2:
            j1 = idx[(i, 1)]
            i2b, k2 = labels[perm[j1]]
            if i2b != i2:
                return None
            u = (k2 - b_i) % d
            if u_global is None:
                u_global = u
            elif u != u_global:
                return None
    if u_global is None:
        u_global = 1
    for j, (i, k) in enumerate(labels):
        i2, k2 = labels[perm[j]]
        if i2 != sigma[i] or k2 != (u_global * k + b[i]) % d:
            return None
    return u_global, sigma, b


# ----------------------------------------------------------------------------
# one lacunary pencil (families A and B)
# ----------------------------------------------------------------------------

def check_lacunary(q: int, d: int, m: int, K: int = 30, verbose: bool = True, phase: int = None) -> Dict:
    n = d * m
    assert q % 2 == 1 and math.gcd(d * m, q) == 1 and math.gcd(m - 1 if m > 1 else 1, q) == 1
    if m == 1:
        f_t = [[0, q - 1]] + [[0]] * (n - 1) + [[1]]                     # x^d - t
    else:
        f_t = [[0, q - 1]] + [[0]] * (d - 1) + [[q - 1]] + [[0]] * (n - d - 1) + [[1]]   # x^{dm} - x^d - t
    rec: Dict = {"family": "A" if m == 1 else "B", "q": q, "d": d, "m": m, "MV": n, "f": f_t}
    # a point with squarefree specialization
    t0 = None
    Fp = hf.Zmod(q)
    import verify_roots as vr
    for cand in range(q):
        f0 = [hf._peval(Fp, a, cand) for a in f_t]
        if vr._is_squarefree(Fp, f0):
            t0 = cand; break
    assert t0 is not None
    rec["t0"] = t0
    state = cf.FqtState(f_t, q, t0, K)
    rec["s"] = state.s
    labels, _ = fibration_labels(state, d)
    W_cl, A_cl = classification_groups(labels, d, m, q)
    rec["W_cl_order"], rec["A_cl_order"] = len(W_cl), len(A_cl)
    # certified Frobenius: affine with multiplier exactly q
    aff = affine_data(state.tau, labels, d, m)
    rec["tau_affine_multiplier_q"] = aff is not None and aff[0] == q % d
    # descent from the proven bound A_cl (arithmetic), then geometric from G (G_geom <= G, tau in G).
    # phase support: for large pencils the two descents run in separate invocations,
    # with G's generators passed through a scratch file (the state rebuild is deterministic).
    import os
    scratch = f"scratch_lacunary_{q}_{d}_{m}.json"
    if os.path.exists(scratch):
        G = pg.closure([tuple(x) for x in json.load(open(scratch))["G_gens"]], n)
        assert state.tau in G and G <= A_cl
    else:
        G, _ = cf.galois_group_Fqt(state, e=1, verbose=False, U0=A_cl)
        if phase == 1:
            json.dump({"G_gens": [list(g) for g in pg.generating_set(G, n)]}, open(scratch, "w"))
            rec["phase1_G_order"] = len(G)
            return rec
    Ggeo, _ = cf.galois_group_Fqt(state, e=state.s, verbose=False, U0=G)
    if os.path.exists(scratch):
        os.remove(scratch)
    assert Ggeo <= G
    c = len(G) // len(Ggeo)
    rec["G_order"], rec["G_geom_order"], rec["c"] = len(G), len(Ggeo), c
    # classification comparisons (literal containment in the labelling)
    rec["G_geom_in_W_cl"] = Ggeo <= W_cl
    rec["G_in_A_cl"] = G <= A_cl
    ad_geo = [affine_data(x, labels, d, m) for x in Ggeo]
    rec["G_geom_multipliers_trivial"] = all(a is not None and a[0] % d == 1 % d for a in ad_geo)
    powers_of_q = {pow(q, a, d) for a in range(ord_mod(q, d))} if d > 1 else {0}
    ad_all = [affine_data(x, labels, d, m) for x in G]
    rec["G_multipliers_in_<q>"] = all(a is not None and (a[0] in powers_of_q if d > 1 else True) for a in ad_all)
    rec["c_equals_ord_d_q"] = (c == ord_mod(q, d))
    rec["G_geom_equals_W_cl"] = (Ggeo == W_cl)
    rec["G_equals_A_cl_semidirect"] = (len(G) == len(W_cl) * ord_mod(q, d)) if rec["G_geom_equals_W_cl"] else None
    rec["ok"] = all(rec[k] for k in ("tau_affine_multiplier_q", "G_geom_in_W_cl", "G_in_A_cl",
                                     "G_geom_multipliers_trivial", "G_multipliers_in_<q>", "c_equals_ord_d_q"))
    if verbose:
        print(f"F_{q} d={d:2d} m={m} MV={n:2d}: |W_cl|={len(W_cl):4d} |G_geom|={len(Ggeo):4d} "
              f"{'= W_cl' if rec['G_geom_equals_W_cl'] else '< W_cl'} | |G|={len(G):4d} <= |A_cl|={len(A_cl):4d} "
              f"| c={c} (= ord_{d}({q}): {rec['c_equals_ord_d_q']}) | {'all ok' if rec['ok'] else 'FAILURE'}")
    return rec


