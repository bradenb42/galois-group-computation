"""
family_sparse.py — validation family 3: specializations to F_q(t) of lacunary
and triangular sparse systems with mixed volume up to 40.

Families (univariate pencils; MV = deg_x f = number of solutions):

  A. pure lacunary      f = x^d - t                (MV = d, up to 40)
  B. lacunary trinomial f = x^{dm} - x^d - t = g(x^d), g = y^m - y - t
                                                   (MV = dm, up to 16)
  C. triangular         f = g(h(x)) for sparse g, h (MV = 6 here)

Classification (Esterov's dichotomy, specialized to a one-parameter pencil;
the containments below are PROVEN for every pencil, equality holds for the
full coefficient space and is expected/observed for generic pencils):

  * the fibres of x -> x^d and the mu_d-torsor structure on each fibre are
    defined over F_q(t); every Galois element acts on a fixed primitive
    zeta_d by a single power (the cyclotomic character). Hence in the natural
    labelling (fibre i, cyclic label k):

        G_geom <= W_cl = C_d wr S_m            (multiplier 1)
        G      <= A_cl = (C_d wr S_m) x| <q mod d>   (global multiplier in <q>)

    and the certified Frobenius at any F_q-point has multiplier exactly q.
  * [G : G_geom] = c is the constant field degree (A7); for the pencils here
    the constants are generated by zeta_d (the base g = y^m - y - t has c = 1),
    so the prediction is c = ord_d(q).
  * triangular: fibre blocks of h are proven; the block quotient of G_geom is
    the geometric monodromy of g (computed independently), and
    G_geom <= L wr (quotient) for the relative local group L.

Everything group-theoretic is checked as literal containment of permutation
sets in the natural labelling — no conjugacy searches. The descent starts at
the PROVEN bound A_cl (recorded in the result), which is what makes MV = 40
feasible (|A_cl| = d phi(d) = 640 for d = 40, versus |S_40|).

Results accumulate in family_sparse_results.json (resumable, time budget).
"""

